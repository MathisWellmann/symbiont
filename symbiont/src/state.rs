//! Agent state that lives between calls: a value the dylib defines and the
//! host owns.
//!
//! An `evolvable!` block that declares `type State: Default + Send +
//! 'static;` lets its functions take `state: &mut State` (or `&State`) as an
//! argument. The agent defines the type in its candidate
//! (`#[derive(Default)] struct State { .. }`), and the host holds one
//! [`State`] per run, created with [`crate::Runtime::new_state`].
//!
//! # Who owns what
//!
//! The dylib allocates the value with its `State::default()`, and the dylib
//! frees it: only its code knows the type, the layout and the drop glue. The
//! host's [`State`] is a type-erased handle: a thin pointer to the value,
//! the tag of the dylib that created it, the revision id, the dylib's drop
//! function, and a reference that pins the revision. Its `#[repr(C)]` prefix
//! is the `Handle` the dylib reads (`state_preamble.rs`).
//!
//! # A state belongs to one revision
//!
//! Revisions are compiled from the same crate name, so their `State` types
//! can share a path and a `TypeId` while their layouts differ. The tag is
//! therefore not a type id but the address of a static inside the dylib that
//! created the value. Every export wrapper compares it with its own before it
//! touches the value, and aborts the process on a mismatch: that is a bug in
//! the host, and any access would be undefined behaviour.
//!
//! # Unload safety
//!
//! The drop code lives in the dylib, so a [`State`] pins its revision like a
//! [`crate::RevisionFn`] does: [`crate::Runtime::unload_revision`] reports
//! the revision as [`crate::Unloaded::Pinned`] and unmaps it only after the
//! last state (and handle) is gone. The state's value is dropped first, then
//! the pin is released.

use std::{
    fmt,
    sync::Arc,
};

use crate::Revision;

/// The dylib's state protocol (`state_preamble.rs`), injected into every
/// generated crate whose `evolvable!` block declares `type State`.
pub(crate) const STATE_PREAMBLE: &str = include_str!("state_preamble.rs");

/// The module of the generated crate that holds [`STATE_PREAMBLE`].
pub(crate) const STATE_MODULE: &str = "__symbiont_state";

/// Exported by the dylib: allocate `State::default()`, or return null if it
/// panicked (the message is in the revision's panic buffer).
pub(crate) const NEW_SYMBOL: &str = "__symbiont_state_new";
/// Exported by the dylib: free a value that [`NEW_SYMBOL`] returned.
pub(crate) const DROP_SYMBOL: &str = "__symbiont_state_drop";
/// Exported by the dylib: the tag of that dylib.
pub(crate) const TAG_SYMBOL: &str = "__symbiont_state_tag";

/// Signature of [`NEW_SYMBOL`].
pub(crate) type NewFn = fn() -> *mut ();
/// Signature of [`DROP_SYMBOL`]. `unsafe`: the pointer must come from the
/// same dylib's [`NewFn`] and is freed.
pub(crate) type DropFn = unsafe fn(*mut ());
/// Signature of [`TAG_SYMBOL`].
pub(crate) type TagFn = fn() -> usize;

/// The `type State` declaration of an `evolvable!` block, generated by the
/// macro. Every [`crate::EvolvableDecl`] of the block points to the same one.
#[derive(Debug, PartialEq, Eq)]
pub struct StateDecl {
    /// The declared bounds, e.g. `"Default + Send + 'static"`. The generated
    /// dylib asserts that the agent's `State` satisfies them.
    pub bounds: &'static str,
    /// The definition of `State` in the initial revision: the `struct State`
    /// or `enum State` of the `evolvable!` block, or a unit struct deriving
    /// `Default` if the block has none.
    pub initial: &'static str,
}

/// The state value of one revision, owned by the host.
///
/// Create it with [`crate::Runtime::new_state`] (or the `new_state` function
/// that `evolvable!` generates), and pass it as `&mut State` to the evolvable
/// functions of the same revision. One state per independent run keeps runs
/// isolated and deterministic.
///
/// A state works only with the revision that created it; see
/// [`State::revision`]. Calls with the state of another revision abort the
/// process. When the active revision changes, create a new state.
///
/// The value is opaque to the host: it cannot be read, cloned, or
/// serialized. A restart or a revision swap starts from `State::default()`.
#[repr(C)]
#[must_use = "a state is only useful if it is passed to the evolvable functions"]
pub struct State {
    // The first three fields are the `Handle` the dylib reads. Keep their
    // order and types in sync with `state_preamble.rs`; the tests check it.
    /// The dylib's leaked `Box<State>`, as a thin pointer. Never null.
    data: *mut (),
    /// The tag of the dylib that created `data`. Never zero.
    tag: usize,
    /// The raw id of the revision that created `data`.
    revision: u64,
    // Host-only fields.
    /// The dylib's drop function for `data`.
    drop_fn: DropFn,
    /// Keeps the dylib mapped while `data` and `drop_fn` point into it.
    /// Declared last so it drops after [`Drop::drop`] freed the value.
    _pin: Arc<dyn Send + Sync>,
}

// SAFETY: the value behind `data` is `Send`: the generated dylib asserts the
// declared `Send` bound on the agent's `State`. The handle is deliberately
// not `Sync`: a shared `&State` reaches the value through `&State`
// arguments, which would need `State: Sync` as well.
unsafe impl Send for State {}

impl State {
    /// Assemble a state from the parts the dylib returned.
    ///
    /// # Safety
    ///
    /// `data` must be a value that the dylib's `__symbiont_state_new`
    /// returned, `tag` that dylib's tag, `drop_fn` that dylib's drop
    /// function, and `pin` must keep that dylib mapped. `data` must not be
    /// used by anything else.
    pub(crate) unsafe fn from_raw_parts(
        data: *mut (),
        tag: usize,
        revision: Revision,
        drop_fn: DropFn,
        pin: Arc<dyn Send + Sync>,
    ) -> Self {
        assert!(!data.is_null(), "a state value is never null");
        assert_ne!(tag, 0, "a dylib tag is the address of a static");
        Self {
            data,
            tag,
            revision: revision.as_u64(),
            drop_fn,
            _pin: pin,
        }
    }

    /// The revision that created this state, and the only one whose
    /// functions accept it.
    #[must_use]
    pub fn revision(&self) -> Revision {
        Revision::new(self.revision)
    }
}

impl Drop for State {
    fn drop(&mut self) {
        debug_assert!(!self.data.is_null());
        // SAFETY: `data` came from the dylib whose `drop_fn` this is
        // (`from_raw_parts` contract), and `_pin` keeps that dylib mapped
        // until after this returns. `data` is not used again.
        unsafe { (self.drop_fn)(self.data) };
    }
}

impl fmt::Debug for State {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("State")
            .field("revision", &self.revision)
            .finish_non_exhaustive()
    }
}

#[cfg(test)]
mod tests {
    use std::{
        mem::offset_of,
        sync::{
            Arc,
            Mutex,
            atomic::{
                AtomicUsize,
                Ordering,
            },
        },
    };

    use super::*;

    /// The exact state protocol that ships inside every generated dylib,
    /// compiled into this test binary so Miri executes it.
    #[allow(
        unused,
        unreachable_pub,
        reason = "the preamble is compiled verbatim; in a dylib its items are used by the glue"
    )]
    mod preamble {
        include!("state_preamble.rs");
    }

    /// Records the order of the events the drop tests care about. Each test
    /// uses its own log, so they can run in parallel.
    type Log = Arc<Mutex<Vec<&'static str>>>;

    /// What an agent's `State` could look like: heap data and drop glue.
    #[derive(Default)]
    struct AgentState {
        fills: Vec<f64>,
        steps: usize,
        log: Option<Log>,
    }

    impl Drop for AgentState {
        fn drop(&mut self) {
            if let Some(log) = &self.log {
                log.lock().expect("log lock").push("value dropped");
            }
        }
    }

    /// Stands in for the `RevisionEntry` a state pins.
    struct Pin(Log);

    impl Drop for Pin {
        fn drop(&mut self) {
            self.0.lock().expect("log lock").push("pin released");
        }
    }

    /// The drop export the glue generates, for `AgentState`.
    unsafe fn drop_agent_state(data: *mut ()) {
        // SAFETY: the tests only pass values from `preamble::new::<AgentState>`.
        unsafe { preamble::drop_state::<AgentState>(data) };
    }

    fn new_state(pin: Arc<dyn Send + Sync>) -> State {
        let data = preamble::new::<AgentState>();
        // SAFETY: `data` comes from the preamble's `new`, with its tag and
        // the matching drop function. The test binary is never unmapped.
        unsafe {
            State::from_raw_parts(
                data,
                preamble::tag(),
                Revision::new(3),
                drop_agent_state,
                pin,
            )
        }
    }

    /// The dylib's view of `state`: the pointer the ABI passes for a
    /// `&mut State` argument, read as the `Handle` prefix.
    fn handle(state: &mut State) -> &mut preamble::Handle {
        // SAFETY: `State` is `repr(C)` and starts with the fields of
        // `Handle` (checked in `handle_is_a_prefix_of_the_state`).
        unsafe { &mut *std::ptr::from_mut(state).cast::<preamble::Handle>() }
    }

    #[test]
    fn handle_is_a_prefix_of_the_state() {
        assert_eq!(offset_of!(State, data), 0);
        assert_eq!(offset_of!(State, tag), size_of::<*mut ()>());
        assert_eq!(
            offset_of!(State, revision),
            size_of::<*mut ()>() + size_of::<usize>()
        );
        assert!(size_of::<State>() > size_of::<preamble::Handle>());
        assert!(align_of::<State>() >= align_of::<preamble::Handle>());
        // The preamble's offsets, computed the same way.
        let mut state = new_state(Arc::new(()));
        let base = std::ptr::from_mut(&mut state).addr();
        let handle = handle(&mut state);
        assert_eq!(std::ptr::from_mut(handle).addr(), base);
        assert!(preamble::is_own(handle));
    }

    #[test]
    fn the_value_survives_between_calls() {
        let mut state = new_state(Arc::new(()));
        assert_eq!(state.revision(), Revision::new(3));
        for step in 1..=3 {
            // SAFETY: the state was created by this "dylib" for `AgentState`.
            let value = unsafe { preamble::state_mut::<AgentState>(handle(&mut state), "step") };
            value.steps += 1;
            value.fills.push(f64::from(step));
            assert_eq!(value.steps, usize::try_from(step).expect("small"));
        }
        // SAFETY: as above, shared.
        let value = unsafe { preamble::state_ref::<AgentState>(handle(&mut state), "peek") };
        assert_eq!(value.steps, 3);
        assert_eq!(value.fills, [1.0, 2.0, 3.0]);
    }

    #[test]
    fn the_value_drops_before_the_pin() {
        let log: Log = Arc::default();
        let mut state = new_state(Arc::new(Pin(Arc::clone(&log))));
        // SAFETY: the state was created by this "dylib" for `AgentState`.
        let value = unsafe { preamble::state_mut::<AgentState>(handle(&mut state), "step") };
        value.log = Some(Arc::clone(&log));
        assert!(log.lock().expect("log lock").is_empty());
        drop(state);
        assert_eq!(
            *log.lock().expect("log lock"),
            ["value dropped", "pin released"],
            "the dylib's drop code must run while the dylib is still pinned"
        );
    }

    #[test]
    fn a_state_moves_to_another_thread() {
        let mut state = new_state(Arc::new(()));
        let state = std::thread::spawn(move || {
            // SAFETY: the state was created by this "dylib" for `AgentState`.
            let value = unsafe { preamble::state_mut::<AgentState>(handle(&mut state), "step") };
            value.steps = 7;
            state
        })
        .join()
        .expect("thread does not panic");
        assert_eq!(state.revision(), Revision::new(3));
    }

    #[test]
    fn another_dylibs_tag_is_not_own() {
        let mut state = new_state(Arc::new(()));
        let own = preamble::tag();
        assert_ne!(own, 0);
        // A state of another dylib carries another tag. Build one by hand:
        // the drop function must still be the one that matches `data`.
        // SAFETY: matching `new` and drop function; only the tag is foreign,
        // and the value is never accessed through it.
        let mut foreign = unsafe {
            State::from_raw_parts(
                preamble::new::<AgentState>(),
                own + 1,
                Revision::new(4),
                drop_agent_state,
                Arc::new(()),
            )
        };
        assert!(!preamble::is_own(handle(&mut foreign)));
        assert!(preamble::is_own(handle(&mut state)));
    }

    #[test]
    fn each_state_drops_its_value_exactly_once() {
        static DROPS: AtomicUsize = AtomicUsize::new(0);
        #[derive(Default)]
        struct Counted;
        impl Drop for Counted {
            fn drop(&mut self) {
                DROPS.fetch_add(1, Ordering::Relaxed);
            }
        }
        unsafe fn drop_counted(data: *mut ()) {
            // SAFETY: only values of `preamble::new::<Counted>` reach here.
            unsafe { preamble::drop_state::<Counted>(data) };
        }
        let states = Vec::from_iter((0..4).map(|_| {
            // SAFETY: matching `new`, tag and drop function.
            unsafe {
                State::from_raw_parts(
                    preamble::new::<Counted>(),
                    preamble::tag(),
                    Revision::INITIAL,
                    drop_counted,
                    Arc::new(()),
                )
            }
        }));
        assert_eq!(DROPS.load(Ordering::Relaxed), 0);
        drop(states);
        assert_eq!(DROPS.load(Ordering::Relaxed), 4);
    }

    #[test]
    #[should_panic(expected = "a state value is never null")]
    fn a_null_value_is_rejected() {
        // SAFETY: rejected before anything is stored.
        let _ = unsafe {
            State::from_raw_parts(
                std::ptr::null_mut(),
                preamble::tag(),
                Revision::INITIAL,
                drop_agent_state,
                Arc::new(()),
            )
        };
    }

    #[test]
    fn a_zero_tag_is_rejected() {
        let data = preamble::new::<AgentState>();
        let rejected = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| {
            // SAFETY: rejected before anything is stored.
            unsafe {
                State::from_raw_parts(data, 0, Revision::INITIAL, drop_agent_state, Arc::new(()))
            }
        }));
        let message = rejected.expect_err("a zero tag is rejected");
        let message = message
            .downcast_ref::<String>()
            .expect("assert_ne! formats its message");
        assert!(message.contains("a dylib tag is the address of a static"));
        // SAFETY: `data` was not stored anywhere, so it is freed only here.
        unsafe { drop_agent_state(data) };
    }
}
